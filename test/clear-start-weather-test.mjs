import assert from 'node:assert/strict';
import { startupWeather, restoreWeather, weatherSnapshot } from '../src/flight-weather.js';
import { Weather, WEATHER } from '../src/weather.js';

const stale = { fog: .85, gloom: .6, rain: .5, bolts: 1 };
const fresh = startupWeather({});
assert.equal(fresh.weather, 'clear');
assert.equal(fresh.metarAuto, false);
assert.equal(fresh.vis, WEATHER.clear.vis);
assert.equal(fresh.clouds, WEATHER.clear.clouds);
const normal = startupWeather({ weather: 'metar', metarAuto: true, metarWx: stale, vis: .3, clouds: 1, aircraft: 'f27' });
assert.deepEqual({ id: normal.weather, auto: normal.metarAuto, snapshot: normal.metarWx, vis: normal.vis, aircraft: normal.aircraft }, { id: 'clear', auto: false, snapshot: undefined, vis: WEATHER.clear.vis, aircraft: 'f27' });
const chosen = startupWeather({ weather: 'fog', metarAuto: true, metarWx: stale, vis: .3 });
assert.equal(chosen.weather, 'fog');
assert.equal(chosen.vis, WEATHER.fog.vis);
assert.equal(chosen.metarAuto, false);
assert.equal(chosen.metarWx, undefined);
const live = startupWeather({ ...normal, weather: 'metar', metarAuto: true, metarWx: stale, vis: .3 });
assert.equal(live.metarAuto, true);
assert.deepEqual(live.metarWx, stale);
assert.equal(restoreWeather(normal, weatherSnapshot(live)), true);
assert.deepEqual(normal.metarWx, stale);
const el = () => ({style: {}});
const gloom = el(), fog = el(), bolt = el(), screen = new Weather({getContext: () => ({})}, gloom, fog, bolt);
screen.set(WEATHER.fog, true);
assert.equal(+fog.style.opacity, WEATHER.fog.fog);
screen.set(WEATHER.clear, true);
assert.deepEqual([+fog.style.opacity, screen.fogV, screen.fogTarget, +gloom.style.opacity, +bolt.style.opacity], [0,0,0,0,0]);
console.log('PASS clear startup, legacy live fog migration, explicit fog/modern live preservation, and immediate fog reset');
